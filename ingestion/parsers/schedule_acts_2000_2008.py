def _build_records(
    year: int,
    source_filename: str,
    file_tag: str,
    rows: List[ScheduleRow],
) -> List[dict]:
    """Converts ScheduleRow tuples into canonical raw_records dicts."""
    id_prefix = f"P-{year}-{file_tag}" if file_tag else f"P-{year}"
    records: List[dict] = []
    for idx, (page, head, agency, title, spending_type, amount) in enumerate(rows, 1):
        records.append({
            "id": f"{id_prefix}-{idx:05d}",
            "budgetCode": head.split("-")[0],
            "projectCode": head,
            "projectName": title,
            "agency": agency,
            "sector": infer_sector(agency, title),
            "spendingType": spending_type,
            "financialYear": year,
            "amount": int(amount),
            "projectType": "ONGOING",
            "page": page,
            "sourceFile": source_filename,
        })
    return records


def get_schedule_act_records(
    year: int,
    filename: str,
    file_tag: str = "",
) -> Optional[List[dict]]:
    """
    Returns verbatim Gazette Schedule records for supported 2000-2008 Appropriation Act PDFs,
    or None if the file should be parsed by standard PDF text extraction.
    """
    key = (int(year), (filename or "").strip().lower())
    rows = SCHEDULE_REGISTRY.get(key)
    if rows is None:
        return None
    return _build_records(int(year), filename, file_tag, rows)
